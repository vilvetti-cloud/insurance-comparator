from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable


@dataclass(frozen=True)
class OfficialSnapshot:
    field_key: str
    value: str
    source_url: str
    title: str
    source_level: int = 2
    confidence: float = 0.9
    direct: bool = True
    evidence: str | None = None


def _s(
    field_key: str,
    value: str,
    source_url: str,
    title: str,
    *,
    level: int = 2,
    confidence: float = 0.9,
    direct: bool = True,
    evidence: str | None = None,
) -> OfficialSnapshot:
    return OfficialSnapshot(
        field_key=field_key,
        value=value,
        source_url=source_url,
        title=title,
        source_level=level,
        confidence=confidence,
        direct=direct,
        evidence=evidence or value,
    )


